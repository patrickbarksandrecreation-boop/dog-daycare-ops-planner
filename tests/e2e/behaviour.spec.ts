import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
async function demo(page: Page) {
  await page.goto('/'); await page.getByLabel('Demo scenario').selectOption('planned');
  await page.getByRole('button',{name:'Explore the demo'}).click();
  await expect(page.getByTestId('booked-count')).toHaveText('100');
}
async function info(page: Page,name:string) { await page.getByRole('button',{name:`Information for ${name}`,exact:true}).click(); }
test('multiline notes save, cancel, refresh and offline gating',async({page,context})=>{
  await demo(page); await info(page,'Alfie');
  await page.getByRole('button',{name:'Edit notes',exact:true}).click();
  await page.getByLabel('Handling notes',{exact:true}).fill('Fictional calm greeting.\nGive space at the gate.');
  await page.getByRole('button',{name:'Save notes',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Handling notes saved.'})).toBeVisible();
  await page.getByRole('button',{name:'Edit notes',exact:true}).click();
  await page.getByLabel('Handling notes',{exact:true}).fill('Discard me');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await expect(page.getByRole('dialog')).not.toContainText('Discard me');
  await page.reload(); await demo(page); await info(page,'Alfie');
  await expect(page.getByRole('dialog')).toContainText('Give space at the gate.');
  await context.setOffline(true);
  await expect(page.getByRole('button',{name:'Edit notes',exact:true})).toBeDisabled();
  await expect(page.getByRole('button',{name:'Add rule',exact:true})).toBeDisabled();
  await expect(page.getByRole('dialog')).toContainText('Fictional calm greeting.');
  await context.setOffline(false);
});
test('search selector excludes self, blocks duplicates, creates symmetric rules and supports editing/removal',async({page})=>{
  await demo(page); await info(page,'Alfie');
  await page.getByRole('button',{name:'Add rule',exact:true}).click();
  await expect(page.getByRole('button',{name:'Choose Alfie',exact:true})).toHaveCount(0);
  await page.getByLabel('Search dogs',{exact:true}).fill('Archie');
  await expect(page.getByRole('button',{name:'Choose Archie · rule already exists',exact:true})).toBeDisabled();
  await page.getByLabel('Search dogs',{exact:true}).fill('Mixed breed');
  await expect(page.getByRole('button',{name:'Choose Bailey',exact:true})).toContainText('Mixed breed');
  await expect(page.getByRole('button',{name:'Choose Bailey',exact:true}).locator('.avatar')).toHaveCount(1);
  await page.getByRole('button',{name:'Choose Bailey',exact:true}).click();
  await page.getByLabel('Rule level').selectOption('soft');
  await expect(page.getByRole('button',{name:'Save rule',exact:true})).toBeDisabled();
  await page.getByLabel('Rule note').fill('Fictional instruction: monitor introductions.');
  await page.getByRole('button',{name:'Save rule',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('Bailey — Soft · Monitor closely and assess.');
  await page.getByRole('button',{name:'Close dialog'}).click(); await info(page,'Bailey');
  await expect(page.getByRole('dialog')).toContainText('Alfie — Soft · Monitor closely and assess.');
  await page.getByRole('button',{name:'Edit rule with Alfie',exact:true}).click();
  await page.getByLabel('Rule level').selectOption('hard'); await page.getByLabel('Rule note').fill('Fictional instruction: separate play groups.');
  await page.getByRole('button',{name:'Save rule',exact:true}).click();
  await page.getByRole('button',{name:'Remove rule with Alfie',exact:true}).click();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('Alfie — Hard · Must not mix.');
  await page.getByRole('button',{name:'Remove rule with Alfie',exact:true}).click();
  await page.getByRole('button',{name:'Confirm removal',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('No configured interaction rules.');
  await page.getByRole('button',{name:'Close dialog'}).click(); await info(page,'Alfie');
  await expect(page.getByRole('button',{name:'Edit rule with Bailey',exact:true})).toHaveCount(0);
});
test('hard warnings are red even when planned and remain advisory through movement and attendance',async({page})=>{
  await demo(page);
  await expect(page.getByTestId('warnings-group-1')).toHaveClass(/live-warning/);
  await expect(page.getByTestId('warnings-group-1')).toContainText('Hard · Must not mix.');
  await expect(page.getByTestId('warnings-group-1')).toContainText('planned conflict');
  await expect(page.getByTestId('warnings-group-2')).toHaveClass(/planned-warning/);
  await expect(page.getByTestId('warnings-group-2')).toContainText('Soft');
  await page.getByRole('button',{name:'View warnings for Group 1'}).click();
  await expect(page.getByRole('dialog')).toContainText('Alfie + Archie');
  await expect(page.getByRole('dialog')).toContainText('Keep Alfie and Archie in separate play groups.');
  await page.getByRole('button',{name:'Close dialog'}).click();
  await info(page,'Archie'); await page.getByLabel('Move dog to').selectOption('group-2');
  await page.getByLabel('Move dog to').selectOption('group-1');
  await page.getByRole('button',{name:'Mark present',exact:true}).click();
  await expect(page.getByRole('button',{name:'Mark departed',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Mark departed',exact:true}).click();
  await expect(page.getByTestId('warnings-group-1')).not.toContainText('Hard');
});
test('two demo tabs sync notes and rules, retain drafts on conflicts and preserve removals after reload',async({page,context})=>{
  await demo(page); await info(page,'Alfie'); await page.getByRole('button',{name:'Edit notes',exact:true}).click();
  const other=await context.newPage(); await demo(other); await info(other,'Alfie');
  await other.getByRole('button',{name:'Edit notes',exact:true}).click();
  await other.getByLabel('Handling notes',{exact:true}).fill('Other handler saved this');
  await other.getByRole('button',{name:'Save notes',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('These notes changed while you were editing.');
  await expect(page.getByRole('button',{name:'Save notes',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('Other handler saved this');
  await page.getByRole('button',{name:'Edit rule with Archie'}).click();
  await other.getByRole('button',{name:'Edit rule with Archie'}).click();
  await other.getByLabel('Rule level').selectOption('soft');
  await other.getByLabel('Rule note').fill('Shared changed rule');
  await other.getByRole('button',{name:'Save rule',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('This rule changed or was removed.');
  await expect(page.getByRole('button',{name:'Save rule',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await other.getByRole('button',{name:'Remove rule with Archie'}).click();
  await other.getByRole('button',{name:'Confirm removal'}).click();
  await expect(page.getByRole('dialog')).toContainText('No configured interaction rules.');
  await page.reload(); await demo(page); await info(page,'Archie');
  await expect(page.getByRole('dialog')).toContainText('No configured interaction rules.');
});
test('mobile keyboard editing keeps controls in view',async({page})=>{
  await page.setViewportSize({width:390,height:844}); await demo(page); await info(page,'Alfie');
  await page.getByRole('button',{name:'Edit notes',exact:true}).press('Enter');
  await expect(page.getByLabel('Handling notes',{exact:true})).toBeFocused();
  await page.keyboard.type('Fictional keyboard note');
  await page.getByRole('button',{name:'Save notes',exact:true}).press('Enter');
  await expect(page.getByRole('dialog')).toContainText('Handling notes saved.');
  await page.getByRole('button',{name:'Add rule',exact:true}).press('Enter');
  await page.getByLabel('Search dogs',{exact:true}).fill('Bailey');
  await page.getByRole('button',{name:'Choose Bailey',exact:true}).press('Enter');
  await page.getByLabel('Rule note').fill('Fictional keyboard rule');
  await page.getByRole('button',{name:'Save rule',exact:true}).press('Enter');
  await expect(page.getByRole('dialog')).toContainText('Bailey — Hard · Must not mix.');
  const box=await page.getByRole('dialog').boundingBox(); expect(box!.width).toBeLessThanOrEqual(390);
  await page.screenshot({path:'docs/screenshots/handling-rules-mobile.png'});
});
